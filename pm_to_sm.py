#!/usr/bin/env python3
"""
pm_to_sm.py - Convert a Bitwarden Password Manager (unencrypted JSON) export
into a Bitwarden Secrets Manager import file.

Mapping:
    Collection            -> Project   (name = collection name)
    Secure note (type 2)  -> Secret    (key = item name, value = note body)
    Custom fields         -> appended to the secret's "note" field

Only secure notes that belong to a collection present in the export's
"collections" list are migrated by default. Use --include-unassigned to also
migrate secure notes that have no (known) collection; they'll be imported as
secrets with no project.

Usage:
    python3 pm_to_sm.py bitwarden_export.json -o sm_import.json
    python3 pm_to_sm.py export.json -o out.json --collections "SM" "Hunter Exam"
    python3 pm_to_sm.py export.json -o out.json --exclude-collections "Finance" "HR"
    python3 pm_to_sm.py export.json --dry-run
"""

import argparse
import json
import re
import sys

SECURE_NOTE_TYPE = 2
FIELD_TYPE_NAMES = {0: "text", 1: "hidden", 2: "boolean", 3: "linked"}


class IdGenerator:
    """Produces placeholder IDs in the format Secrets Manager expects.
    Real IDs are generated by Bitwarden on import."""

    def __init__(self):
        self.counter = 0

    def next(self):
        self.counter += 1
        return f"00000000-0000-0000-0000-{self.counter:012d}"


def build_note(item, include_fields=True):
    """Build the secret's 'note' from the item's custom fields (if any)."""
    lines = []
    if include_fields:
        for field in item.get("fields") or []:
            if field.get("type") == 3:  # linked fields have no value of their own
                continue
            name = field.get("name") or "(unnamed)"
            value = field.get("value")
            lines.append(f"{name}: {'' if value is None else value}")
    return "\n".join(lines)


def convert(export, collection_filter=None, exclude_filter=None,
            include_unassigned=False, include_fields=True, skip_empty=True):
    warnings = []

    if export.get("encrypted"):
        sys.exit("ERROR: This export is encrypted. Re-export using the "
                 "unencrypted .json format.")

    collections = {c["id"]: c["name"] for c in export.get("collections", [])}

    if collection_filter:
        wanted = set(collection_filter)
        missing = wanted - set(collections.values())
        for name in sorted(missing):
            warnings.append(f"Collection '{name}' not found in export.")
        collections = {cid: n for cid, n in collections.items() if n in wanted}

    excluded_ids = set()
    if exclude_filter:
        unwanted = set(exclude_filter)
        missing = unwanted - set(collections.values())
        for name in sorted(missing):
            warnings.append(f"Excluded collection '{name}' not found in export.")
        excluded_ids = {cid for cid, n in collections.items() if n in unwanted}
        excluded_names = {cid: n for cid, n in collections.items() if n in unwanted}
        collections = {cid: n for cid, n in collections.items() if n not in unwanted}

    ids = IdGenerator()
    project_ids = {}          # collection id -> placeholder project id
    projects, secrets = [], []
    seen_secrets = set()      # (collection, key, value, note)
    seen_keys = set()         # (collection, key)

    for item in export.get("items", []):
        if item.get("type") != SECURE_NOTE_TYPE:
            continue

        name = item.get("name") or "(unnamed)"
        value = item.get("notes") or ""

        if skip_empty and not value.strip():
            warnings.append(f"Skipped '{name}': secure note body is empty.")
            continue

        item_collections = item.get("collectionIds", [])

        # A note in any excluded collection is never migrated, even if it's
        # also in a collection that is being kept.
        hit = [cid for cid in item_collections if cid in excluded_ids]
        if hit:
            warnings.append(f"Skipped '{name}': in excluded collection "
                            f"'{excluded_names[hit[0]]}'.")
            continue

        known = [cid for cid in item_collections if cid in collections]

        if not known:
            if include_unassigned and not collection_filter:
                target = None
            else:
                warnings.append(f"Skipped '{name}': not in a selected collection.")
                continue
        else:
            target = known[0]
            if len(known) > 1:
                warnings.append(
                    f"'{name}' is in multiple collections; Secrets Manager allows "
                    f"one project per secret, so it was placed in "
                    f"'{collections[target]}' only.")

        note = build_note(item, include_fields)
        project_name = collections[target] if target is not None else "(no project)"

        # Exact duplicate (same project, key, value and note): drop it.
        signature = (target, name, value, note)
        if signature in seen_secrets:
            warnings.append(f"Skipped '{name}' in '{project_name}': exact duplicate "
                            f"of another secret.")
            continue
        seen_secrets.add(signature)

        # Same key but different content in the same project: keep both, but warn.
        key_slot = (target, name)
        if key_slot in seen_keys:
            warnings.append(f"Secret key '{name}' appears more than once in "
                            f"'{project_name}' with different values; both were kept. "
                            f"Consider renaming one before importing.")
        seen_keys.add(key_slot)

        project_list = []
        if target is not None:
            if target not in project_ids:
                pid = ids.next()
                project_ids[target] = pid
                projects.append({"id": pid, "name": collections[target]})
            project_list = [project_ids[target]]

        secrets.append({
            "key": name,
            "value": value,
            "note": note,
            "id": ids.next(),
            "projectIds": project_list,
        })

    # Two different collections with the same name would produce two
    # projects with the same name.
    name_counts = {}
    for pr in projects:
        name_counts[pr["name"]] = name_counts.get(pr["name"], 0) + 1
    for pname, count in name_counts.items():
        if count > 1:
            warnings.append(f"{count} projects will be named '{pname}' because "
                            f"several collections share that name.")

    return {"projects": projects, "secrets": secrets}, warnings


def validate(result):
    """Check the output against Secrets Manager's import rules.
    Returns a list of errors; an empty list means the file is valid."""
    errors = []
    id_pattern = re.compile(
        r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$", re.I)

    if not isinstance(result.get("projects"), list):
        errors.append("Missing 'projects' array.")
    if not isinstance(result.get("secrets"), list):
        errors.append("Missing 'secrets' array.")
    if errors:
        return errors

    all_ids = []
    project_ids = set()
    for pr in result["projects"]:
        pid = pr.get("id", "")
        if not pid or not id_pattern.match(pid):
            errors.append(f"Project '{pr.get('name')}' has a missing or malformed id: '{pid}'.")
        if not pr.get("name"):
            errors.append(f"Project {pid} has no name.")
        project_ids.add(pid)
        all_ids.append(pid)

    for s in result["secrets"]:
        sid = s.get("id", "")
        label = s.get("key") or sid
        if not sid or not id_pattern.match(sid):
            errors.append(f"Secret '{label}' has a missing or malformed id: '{sid}'.")
        if not s.get("key"):
            errors.append(f"Secret {sid} has no key.")
        for field in ("value", "note"):
            if not isinstance(s.get(field), str):
                errors.append(f"Secret '{label}' is missing its '{field}' field.")
        pids = s.get("projectIds")
        if not isinstance(pids, list):
            errors.append(f"Secret '{label}' is missing 'projectIds'.")
            pids = []
        if len(pids) > 1:
            errors.append(f"Secret '{label}' is assigned to {len(pids)} projects; only 1 is allowed.")
        for pid in pids:
            if pid not in project_ids:
                errors.append(f"Secret '{label}' points to project id {pid}, which doesn't exist.")
        all_ids.append(sid)

    seen = set()
    for i in all_ids:
        if i in seen:
            errors.append(f"ID {i} is used more than once.")
        seen.add(i)

    return errors


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("input", help="Unencrypted Bitwarden PM .json export")
    p.add_argument("-o", "--output", default="sm_import.json",
                   help="Output file (default: sm_import.json)")
    group = p.add_mutually_exclusive_group()
    group.add_argument("--collections", nargs="+", metavar="NAME",
                       help="Only migrate these collections (by exact name)")
    group.add_argument("--exclude-collections", nargs="+", metavar="NAME",
                       help="Migrate every collection except these (by exact name). "
                            "Notes in an excluded collection are always skipped.")
    p.add_argument("--include-unassigned", action="store_true",
                   help="Also migrate secure notes with no collection (no project)")
    p.add_argument("--no-fields", action="store_true",
                   help="Don't copy custom fields into the secret's note")
    p.add_argument("--keep-empty", action="store_true",
                   help="Migrate secure notes even if the note body is empty")
    p.add_argument("--dry-run", action="store_true",
                   help="Print a summary only; don't write a file")
    args = p.parse_args()

    with open(args.input, encoding="utf-8") as f:
        export = json.load(f)

    result, warnings = convert(
        export,
        collection_filter=args.collections,
        exclude_filter=args.exclude_collections,
        include_unassigned=args.include_unassigned,
        include_fields=not args.no_fields,
        skip_empty=not args.keep_empty,
    )

    # Summary (never prints secret values)
    proj_names = {pr["id"]: pr["name"] for pr in result["projects"]}
    print(f"Projects: {len(result['projects'])}   Secrets: {len(result['secrets'])}\n")
    for pr in result["projects"]:
        keys = [s["key"] for s in result["secrets"] if pr["id"] in s["projectIds"]]
        print(f"  [{pr['name']}]")
        for k in keys:
            print(f"     - {k}")
    unassigned = [s["key"] for s in result["secrets"] if not s["projectIds"]]
    if unassigned:
        print("  [no project]")
        for k in unassigned:
            print(f"     - {k}")

    if warnings:
        print("\nWarnings:")
        for w in warnings:
            print(f"  ! {w}")

    errors = validate(result)
    if errors:
        print("\nValidation FAILED:")
        for e in errors:
            print(f"  x {e}")
        sys.exit("\nNo file written. Fix the errors above and run again.")
    print(f"\nValidation passed: {len(result['projects']) + len(result['secrets'])} "
          f"unique IDs, all project references valid.")

    if args.dry_run:
        print("\nDry run - no file written.")
        return

    with open(args.output, "w", encoding="utf-8") as f:
        json.dump(result, f, indent=2, ensure_ascii=False)
    print(f"\nWrote {args.output}")
    print("Reminder: this file contains plaintext secrets. Delete it (and the "
          "PM export) after importing. Re-importing creates duplicates.")


if __name__ == "__main__":
    main()
